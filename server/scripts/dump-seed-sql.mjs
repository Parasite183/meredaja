// ─────────────────────────────────────────────────────────────────────
// Generate a SQL file (server/seed-d1.sql) containing the full demo
// seed — schema + data — for Cloudflare D1.
//
// Runs the real seed logic against an in-memory SQLite (so ids and
// hashes come from the same code), then dumps every table to INSERT
// statements.
//
// The seed's sample vault document (and its attachments) are NOT
// dumped — its encrypted blob can't travel through SQL. The worker
// seeds it into R2 at boot instead (seedDemoVault in app.js), so
// the demo vault is populated on Workers with the real enc key and
// the dump never references a blob that doesn't exist.
//
//   Usage:  node server/scripts/dump-seed-sql.mjs
//           npx wrangler d1 execute meredaja-db --remote --file=server/seed-d1.sql
// ─────────────────────────────────────────────────────────────────────
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Env must be set before the db layer evaluates — use dynamic imports.
process.env.DB_FILE = ':memory:';
process.env.DATABASE_URL = '';

const { initDb, db } = await import('../src/db.js');
const { initSchema, schemaDdl } = await import('../src/schema.js');
const { runSeed } = await import('../src/seed.js');

const serverRoot = path.dirname(path.dirname(fileURLToPath(import.meta.url)));

function literal(v) {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'number') return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
}

async function main() {
  await initDb();
  await initSchema();
  await runSeed();

  const { tables, indexes } = schemaDdl();
  const lines = [
    '-- Meredaja demo seed (schema + data) for Cloudflare D1.',
    '-- Generated by server/scripts/dump-seed-sql.mjs.',
    '-- Idempotent: replaces the process library (content) on every run;',
    '-- user/checklist/report rows are INSERT OR IGNORE so re-deploys',
    '-- never wipe real user data.',
    '',
    ...tables.map((t) => t + ';'),
    ...indexes.map((t) => t + ';'),
    '',
  ];

  // `processes` is the content that must propagate: fully replaced on
  // every deploy so edits in server/data/processes/*.json reach
  // production. No FK constraints reference process ids (checklists and
  // reports use process_slug), so a plain DELETE + INSERT is safe.
  lines.push('DELETE FROM processes;');
  lines.push('');

  // Everything else is demo/user data: INSERT OR IGNORE so seed rows
  // land on first deploy and then persist — real users, their
  // checklists, and their step reports are never wiped by a re-deploy.
  // sessions / otp_codes are transient and not part of the seed.
  //
  // The demo users' reports ARE refreshed: INSERT OR IGNORE would skip
  // them forever once their ids exist remotely, so drop those users'
  // reports first (subquery by phone — never touches real users). The
  // three demo users are the distinct reporters behind the demo's
  // promoted step (see seed.js).
  lines.push("DELETE FROM step_reports WHERE user_id IN (SELECT id FROM users WHERE phone IN ('+251911000001', '+251911000002', '+251911000003'));");
  lines.push('');

  for (const t of ['processes', 'users', 'user_checklists', 'checklist_step_status', 'step_reports']) {
    // Seed only the LATEST version of each process — older versions are
    // history rows that nothing resolves against (lookups use
    // ORDER BY version DESC LIMIT 1), and shipping them keeps D1 lean
    // and avoids duplicate-slug inserts against old schemas.
    const rows =
      t === 'processes'
        ? await db.all('SELECT * FROM processes p WHERE version = (SELECT MAX(version) FROM processes WHERE slug = p.slug) ORDER BY id ASC')
        : await db.all(`SELECT * FROM ${t} ORDER BY id ASC`);
    for (const r of rows) {
      const cols = Object.keys(r);
      const vals = cols.map((c) => literal(r[c])).join(', ');
      lines.push(`INSERT OR IGNORE INTO ${t} (${cols.join(', ')}) VALUES (${vals});`);
    }
    lines.push('');
  }

  const out = path.join(serverRoot, 'seed-d1.sql');
  fs.writeFileSync(out, lines.join('\n'));
  console.log(`  ✔ Wrote ${out} (${fs.statSync(out).size} bytes).`);
  console.log('  Apply it to Cloudflare D1 with:');
  console.log('    npx wrangler d1 execute meredaja-db --remote --file=server/seed-d1.sql');
}

main().catch((err) => {
  console.error('Dump failed:', err);
  process.exit(1);
});
